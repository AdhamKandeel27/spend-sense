import "server-only";
import { createClient } from "@supabase/supabase-js";
import { env } from "@/lib/env";

/**
 * Where photos and receipts live. The app only talks to this interface, so
 * moving to other storage later (S3, R2, a server's disk) means adding a
 * driver here, not touching the features.
 */
export interface FileStorage {
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  /** A web stream of the file, or null when it does not exist. */
  get(key: string): Promise<{ body: ReadableStream; size: number } | null>;
  delete(key: string): Promise<void>;
  /**
   * A short-lived URL the browser can PUT one file to, so uploads skip the
   * app server (Vercel caps request bodies at 4.5 MB).
   */
  createUploadUrl(key: string): Promise<string>;
}

// Keys are generated by the app (uuid paths); refuse anything else.
const KEY_PATTERN = /^[a-z0-9-]+(\/[a-z0-9-]+)*\.(webp|jpg|png|pdf|heic|heif|avif|gif)$/;

export function isValidKey(key: string) {
  return KEY_PATTERN.test(key);
}

function assertKey(key: string) {
  if (!isValidKey(key)) throw new Error(`Invalid storage key: ${key}`);
}

/** Reads a whole stored file into memory, or null when it does not exist. */
export async function readFile(store: FileStorage, key: string): Promise<Buffer | null> {
  const file = await store.get(key);
  if (!file) return null;
  return Buffer.from(await new Response(file.body).arrayBuffer());
}

/**
 * Private Supabase Storage bucket. Only the server talks to it, with the
 * secret key, so the bucket needs no public access or policies.
 */
class SupabaseStorage implements FileStorage {
  private bucket;

  constructor(url: string, secretKey: string, bucket: string) {
    const client = createClient(url, secretKey, {
      auth: { persistSession: false, autoRefreshToken: false },
    });
    this.bucket = client.storage.from(bucket);
  }

  async put(key: string, body: Buffer, contentType: string) {
    assertKey(key);
    const { error } = await this.bucket.upload(key, body, { contentType, upsert: false });
    if (error) throw new Error(`Storage upload failed for ${key}: ${error.message}`);
  }

  async get(key: string) {
    assertKey(key);
    const { data, error } = await this.bucket.download(key);
    if (error) {
      const status = (error as { status?: number }).status;
      if (status === 400 || status === 404 || /not found/i.test(error.message)) return null;
      throw new Error(`Storage download failed for ${key}: ${error.message}`);
    }
    return { body: data.stream() as ReadableStream, size: data.size };
  }

  async delete(key: string) {
    assertKey(key);
    const { error } = await this.bucket.remove([key]);
    if (error) throw new Error(`Storage delete failed for ${key}: ${error.message}`);
  }

  async createUploadUrl(key: string) {
    assertKey(key);
    const { data, error } = await this.bucket.createSignedUploadUrl(key);
    if (error) throw new Error(`Could not create an upload URL for ${key}: ${error.message}`);
    return data.signedUrl;
  }
}

// Created on first use, so `next build` (which runs without secrets) can load this module.
let instance: SupabaseStorage | null = null;
const driver = () =>
  (instance ??= new SupabaseStorage(env.NEXT_PUBLIC_SUPABASE_URL, env.SUPABASE_SECRET_KEY, env.SUPABASE_BUCKET));

export const storage: FileStorage = {
  put: (key, body, contentType) => driver().put(key, body, contentType),
  get: (key) => driver().get(key),
  delete: (key) => driver().delete(key),
  createUploadUrl: (key) => driver().createUploadUrl(key),
};
